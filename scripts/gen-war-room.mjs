/**
 * Bakes the war-room dashboard HTML into a TypeScript module.
 *
 * The war-room screen is `src/app/operations-board/war-room.html`, kept as
 * hand-written HTML because it is the exact design that was approved. Serving
 * it needs the bytes at runtime, and neither bundler-specific raw imports nor
 * reading from disk on a serverless host is dependable — so we generate a
 * plain module the route handler can import like any other code.
 *
 * The file is escaped with JSON.stringify, which is safe for the backticks and
 * `${...}` template literals the page's own script uses.
 *
 * Runs automatically before `dev` and `build`; edit the .html, never the .ts.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'src/app/operations-board/war-room.html');
const target = join(root, 'src/app/operations-board/war-room.generated.ts');

const html = readFileSync(source, 'utf8');

writeFileSync(
  target,
  `// GENERATED by scripts/gen-war-room.mjs — do not edit.\n` +
    `// Source: src/app/operations-board/war-room.html\n` +
    `export const WAR_ROOM_HTML = ${JSON.stringify(html)};\n`
);

console.log(`war-room: baked ${html.length} bytes → war-room.generated.ts`);
